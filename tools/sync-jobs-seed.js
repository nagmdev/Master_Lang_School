/*
 * Masters School — regenerates api/_lib/jobs.seed.js from careers.js.
 *
 * The public Careers pages keep their copy in careers.js (SLUGS + the en/ar
 * positions arrays). The admin dashboard manages jobs in the store, whose
 * drivers seed from api/_lib/jobs.seed.js. This script keeps the seed
 * byte-synced with careers.js so the two sources can never drift:
 *
 *   node tools/sync-jobs-seed.js
 *
 * tests/static.test.js asserts the generated output matches the file on disk.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CAREERS_JS = path.join(ROOT, 'careers.js');
const OUT = path.join(ROOT, 'api', '_lib', 'jobs.seed.js');

const src = fs.readFileSync(CAREERS_JS, 'utf8');

// Returns the balanced array/object literal starting at `openIdx`.
function balanced(s, openIdx) {
  const open = s[openIdx];
  const close = open === '[' ? ']' : '}';
  let depth = 0;
  let inStr = false;
  let quote = '';
  for (let i = openIdx; i < s.length; i++) {
    const ch = s[i];
    if (inStr) {
      if (ch === '\\') { i++; continue; }
      if (ch === quote) inStr = false;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') { inStr = true; quote = ch; continue; }
    if (ch === open) depth++;
    else if (ch === close) { depth--; if (depth === 0) return s.slice(openIdx, i + 1); }
  }
  throw new Error('unbalanced literal from index ' + openIdx);
}

// First balanced array literal after `marker`, at/after `fromIndex`.
function firstArrayAfter(marker, fromIndex) {
  const idx = src.indexOf(marker, fromIndex || 0);
  if (idx === -1) throw new Error('could not find ' + JSON.stringify(marker));
  const bracket = src.indexOf('[', idx);
  return Function('return (' + balanced(src, bracket) + ')')();
}

const SLUGS = firstArrayAfter('var SLUGS = [');
const EN = firstArrayAfter('positions: [');
const arBlock = src.indexOf('ar: {');
const AR = firstArrayAfter('positions: [', arBlock);

if (SLUGS.length !== EN.length || EN.length !== AR.length) {
  throw new Error('SLUGS/' + EN.length + '/' + AR.length + ' out of sync');
}

const jobs = SLUGS.map(function (id, i) {
  return { id: id, order: i, en: EN[i], ar: AR[i] };
});

const out = [
  '/*',
  ' * Masters School — job positions seed (source of truth).',
  ' * GENERATED BY tools/sync-jobs-seed.js — DO NOT EDIT BY HAND.',
  ' */',
  "'use strict';",
  '',
  'var SEED_JOBS = ' + JSON.stringify(jobs, null, 2) + ';',
  '',
  'var SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;',
  '',
  'function slugify(title) {',
  "  return String(title || 'job')",
  "    .toLowerCase()",
  "    .replace(/&/g, 'and')",
  "    .replace(/[^a-z0-9]+/g, '-')",
  "    .replace(/^-+|-+$/g, '')",
  "    .slice(0, 60) || 'job';",
  '}',
  '',
  'module.exports = { SEED_JOBS: SEED_JOBS, SLUG_RE: SLUG_RE, slugify: slugify };',
  '',
].join('\n');

fs.writeFileSync(OUT, out, 'utf8');
console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + jobs.length + ' jobs)');